// Generates src/separators.rs: the code points MiniSearch's default tokenizer
// splits on (`/[\n\r\p{Z}\p{P}]+/u`), taken from the JavaScript engine that
// runs this script so the port tracks the browsers' Unicode version rather
// than a Rust crate's. Run after a Node upgrade; `--check` verifies the
// committed file is current.
//
//   node scripts/gen-separators.mjs          # rewrite src/separators.rs
//   node scripts/gen-separators.mjs --check  # exit 1 if it would change
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const target = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'separators.rs')
const separator = /[\p{Z}\p{P}]/u
const ranges = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  if (!separator.test(String.fromCodePoint(cp))) continue
  const last = ranges[ranges.length - 1]
  if (last && last[1] === cp - 1) last[1] = cp
  else ranges.push([cp, cp])
}
const ascii = Array.from({ length: 128 }, (_, cp) => separator.test(String.fromCodePoint(cp)))
const hex = cp => '0x' + cp.toString(16).toUpperCase().padStart(4, '0')

const lines = []
lines.push('//! Separator table for the default tokenizer: every `\\p{Z}` or `\\p{P}` code')
lines.push('//! point, as classified by the JavaScript engine (V8/ICU) MiniSearch runs in.')
lines.push(`//! Generated by \`scripts/gen-separators.mjs\` with Node ${process.versions.node}`)
lines.push(`//! (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). Do not edit by hand.`)
lines.push('')
lines.push(`/// Unicode version of the tables below.`)
lines.push(`pub const UNICODE_VERSION: &str = "${process.versions.unicode}";`)
lines.push('')
lines.push('/// Separator flags for the ASCII range (the hot path).')
lines.push('#[rustfmt::skip]')
lines.push('static ASCII: [bool; 128] = [')
for (let row = 0; row < 128; row += 16) {
  lines.push('    ' + ascii.slice(row, row + 16).map(v => (v ? 'true' : 'false')).join(', ') + ',')
}
lines.push('];')
lines.push('')
lines.push(`/// Inclusive code point ranges, ascending and disjoint (${ranges.length} ranges).`)
lines.push('#[rustfmt::skip]')
lines.push('static RANGES: &[(u32, u32)] = &[')
for (let i = 0; i < ranges.length; i += 4) {
  lines.push('    ' + ranges.slice(i, i + 4).map(([lo, hi]) => `(${hex(lo)}, ${hex(hi)})`).join(', ') + ',')
}
lines.push('];')
lines.push('')
lines.push('/// True for `\\p{Z}` and `\\p{P}` code points (`\\n` and `\\r` are handled by the caller).')
lines.push('#[inline]')
lines.push('#[rustfmt::skip]')
lines.push('pub fn is_separator(character: char) -> bool {')
lines.push('    let code_point = character as u32;')
lines.push('    if code_point < 128 {')
lines.push('        return ASCII[code_point as usize];')
lines.push('    }')
lines.push('    RANGES')
lines.push('        .binary_search_by(|&(low, high)| {')
lines.push('            if code_point < low {')
lines.push('                std::cmp::Ordering::Greater')
lines.push('            } else if code_point > high {')
lines.push('                std::cmp::Ordering::Less')
lines.push('            } else {')
lines.push('                std::cmp::Ordering::Equal')
lines.push('            }')
lines.push('        })')
lines.push('        .is_ok()')
lines.push('}')
lines.push('')
const content = lines.join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch {}
  if (current !== content) {
    console.error(`src/separators.rs is out of date for Node ${process.versions.node} (Unicode ${process.versions.unicode}); run node scripts/gen-separators.mjs`)
    process.exit(1)
  }
  console.log(`src/separators.rs is current (Unicode ${process.versions.unicode}, ${ranges.length} ranges)`)
} else {
  writeFileSync(target, content)
  console.log(`wrote src/separators.rs: Unicode ${process.versions.unicode}, ${ranges.length} ranges`)
}
